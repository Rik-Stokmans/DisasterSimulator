#!/usr/bin/env node

import { readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const auditDirectory = resolve(root, 'audits/municipalities')
const outputPath = resolve(root, 'packages/sim-core/src/audited-municipality-guards.generated.ts')
const checkOnly = process.argv.includes('--check')

const normalize = (value) => String(value ?? '').replace(/\s+/g, ' ').trim()
const sentence = (value) => {
  const normalized = normalize(value)
  if (!normalized) return ''
  return /[.!?]$/.test(normalized) ? normalized : `${normalized}.`
}

const severityOrder = new Map([
  ['critical', 0],
  ['high', 1],
  ['medium', 2],
  ['informational', 3],
])

const entries = []
const auditFiles = (await readdir(auditDirectory))
  .filter((file) => /^GM\d{4}\.json$/.test(file))
  .sort()

for (const file of auditFiles) {
  const audit = JSON.parse(await readFile(resolve(auditDirectory, file), 'utf8'))
  if (audit.verdict !== 'correction-required' && audit.verdict !== 'blocked') continue
  const code = normalize(audit.municipality?.code)
  const name = normalize(audit.municipality?.name)
  if (code !== file.slice(0, 6) || !name) {
    throw new Error(`${file} has an invalid municipality identity for generated audit guards`)
  }
  const findings = Array.isArray(audit.findings)
    ? audit.findings
        .filter((finding) => finding?.status === 'open' && normalize(finding?.summary))
        .map((finding, index) => ({
          index,
          severity: normalize(finding.severity),
          summary: sentence(finding.summary),
        }))
        .sort((left, right) =>
          (severityOrder.get(left.severity) ?? 99) - (severityOrder.get(right.severity) ?? 99) ||
          left.index - right.index,
        )
    : []
  const priorityFindings = findings.slice(0, 6).map((finding) => finding.summary)
  const findingCopy = priorityFindings.length
    ? priorityFindings.join(' ')
    : 'The audit could not establish decision-grade local hazard and service support.'
  const verdictCopy = audit.verdict === 'blocked'
    ? 'is blocked by unresolved evidence or review access'
    : 'is correction-required'
  entries.push([
    code,
    `${name}'s independent municipality audit ${verdictCopy}. ${findingCopy} ` +
      'Until its evidence gates are resolved, official registers and observations remain context, ' +
      'missing or out-of-coverage values remain Unknown/NoData rather than zero or safe, and ' +
      'unsupported local consequence, access, outage and recovery precision is withheld.',
  ])
}

const noteObject = Object.fromEntries(entries)
const output = `// Generated by scripts/generate-audit-guards.mjs from immutable municipality audit artifacts.\n` +
  `// Do not edit this file by hand. Completed correction-required/blocked audits fail closed.\n\n` +
  `export const generatedMunicipalityAuditGuardNotes: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(noteObject, null, 2)})\n\n` +
  `export const generatedMunicipalityAuditGuardCodes = Object.freeze(Object.keys(generatedMunicipalityAuditGuardNotes))\n`

if (checkOnly) {
  let current = ''
  try {
    current = await readFile(outputPath, 'utf8')
  } catch {
    // A missing generated file is stale by definition.
  }
  if (current !== output) {
    throw new Error('Generated municipality audit guards are stale; run `pnpm audit:guards`.')
  }
  console.log(`Municipality audit guards current: ${entries.length}`)
} else {
  await writeFile(outputPath, output, 'utf8')
  console.log(`Generated ${entries.length} fail-closed municipality audit guards`)
}
